// Generic realistic photo template generator for any other Tamil Nadu properties
export function generateGalleryForProperty(property) {
  if (!property) return [];
  const id = property.id;
  if (PROPERTY_SPECIFIC_GALLERIES[id]) {
    return PROPERTY_SPECIFIC_GALLERIES[id];
  }

  // Generate customized, property-appropriate gallery
  const isVilla =
    (property.type || "").toLowerCase().includes("villa") ||
    (property.name || "").toLowerCase().includes("villa");
  const bedrooms = Number(property.bedrooms || 2);
  const city = property.city || "Tamil Nadu";
  const name = property.name || "Property Unit";

  const gallery = [];

  // 1. Exterior
  gallery.push({
    id: `${id}_img_ext`,
    url:
      property.image ||
      (isVilla
        ? "https://images.unsplash.com/photo-1600585154340-be6161a56a0c?auto=format&fit=crop&w=1200&q=80"
        : "https://images.unsplash.com/photo-1545324418-cc1a3fa10c00?auto=format&fit=crop&w=1200&q=80"),
    category: "Exterior",
    caption: `Exterior facade of ${name} in ${city}`,
    order: 1,
  });

  // 2. Living Room
  gallery.push({
    id: `${id}_img_living`,
    url: isVilla
      ? "https://images.unsplash.com/photo-1600607687939-ce8a6c25118c?auto=format&fit=crop&w=1200&q=80"
      : "https://images.unsplash.com/photo-1600565193348-f74bd3c7ccdf?auto=format&fit=crop&w=1200&q=80",
    category: "Living Room",
    caption: `Spacious, well-ventilated living hall with modern flooring in ${name}`,
    order: 2,
  });

  // 3. Kitchen
  gallery.push({
    id: `${id}_img_kitchen`,
    url: "https://images.unsplash.com/photo-1556911220-e15b29be8c8f?auto=format&fit=crop&w=1200&q=80",
    category: "Kitchen",
    caption: `Contemporary Indian modular kitchen with storage cabinets & countertop`,
    order: 3,
  });

  // 4. Master Bedroom
  gallery.push({
    id: `${id}_img_master_bed`,
    url: "https://images.unsplash.com/photo-1595526114035-0d45ed16cfbf?auto=format&fit=crop&w=1200&q=80",
    category: "Master Bedroom",
    caption: `Comfortable master bedroom with natural light and built-in wardrobes`,
    order: 4,
  });

  // 5. Bedroom 2
  if (bedrooms >= 2) {
    gallery.push({
      id: `${id}_img_bed_2`,
      url: "https://images.unsplash.com/photo-1560185127-6ed189bf02f4?auto=format&fit=crop&w=1200&q=80",
      category: "Bedroom 2",
      caption: `Spacious second bedroom with large window overlooking surroundings`,
      order: 5,
    });
  }

  // 6. Bedroom 3
  if (bedrooms >= 3) {
    gallery.push({
      id: `${id}_img_bed_3`,
      url: "https://images.unsplash.com/photo-1598928506311-c55ded91a20c?auto=format&fit=crop&w=1200&q=80",
      category: "Bedroom 3",
      caption: `Third bedroom / home office with ample electrical points and ventilation`,
      order: 6,
    });
  }

  // 7. Bathroom
  gallery.push({
    id: `${id}_img_bath`,
    url: "https://images.unsplash.com/photo-1584622650111-993a426fbf0a?auto=format&fit=crop&w=1200&q=80",
    category: "Bathroom",
    caption: `Modern Western bathroom with branded chrome fittings and geyser provision`,
    order: 7,
  });

  // 8. Balcony / Sit-out
  gallery.push({
    id: `${id}_img_balcony`,
    url: "https://images.unsplash.com/photo-1513694203232-719a280e022f?auto=format&fit=crop&w=1200&q=80",
    category: "Balcony",
    caption: `Private open-air balcony with safety railings in ${city}`,
    order: 8,
  });

  // 9. Dining Area
  gallery.push({
    id: `${id}_img_dining`,
    url: "https://images.unsplash.com/photo-1617806118233-18e1de247200?auto=format&fit=crop&w=1200&q=80",
    category: "Dining Area",
    caption: `Comfortable family dining area positioned close to kitchen`,
    order: 9,
  });

  // 10. Parking
  gallery.push({
    id: `${id}_img_parking`,
    url: "https://images.unsplash.com/photo-1506521781263-d8422e82f27a?auto=format&fit=crop&w=1200&q=80",
    category: "Parking",
    caption: `Dedicated parking bay with easy driveway maneuvering in ${name}`,
    order: 10,
  });

  // 11. Garden / Amenities
  if (
    property.amenities?.some(
      (a) => a.includes("Gym") || a.includes("Pool") || a.includes("Garden") || a.includes("Club")
    ) ||
    isVilla
  ) {
    gallery.push({
      id: `${id}_img_amenity`,
      url: isVilla
        ? "https://images.unsplash.com/photo-1584738766473-61c083514bf4?auto=format&fit=crop&w=1200&q=80"
        : "https://images.unsplash.com/photo-1534438327276-14e5300c3a48?auto=format&fit=crop&w=1200&q=80",
      category: "Amenities",
      caption: `Community recreational amenities & society facilities at ${name}`,
      order: 11,
    });
  }

  return gallery;
}
